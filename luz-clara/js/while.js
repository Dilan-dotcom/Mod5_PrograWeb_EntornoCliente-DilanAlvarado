//uso del while :repetir mientras la condicion sea verdadera (true)

let fotos = 3; //fotos por entregar

while (fotos > 0) {
  console.log(`Entregando la foto ${fotos}`);
  fotos--; //esto lo que hace es resytar hasta fotos sea igual a cero y termnie el prograa y sin eso el siglo seria eterno
}
console.log("todas las fotos entregadas");
