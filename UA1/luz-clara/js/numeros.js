//metodos de math nummber
console.log(Math.round(4.6)); //redondea a cinco(neutral)
console.log(Math.floor(4.6)); //redondea hacia 4 (para abajo)
console.log(Math.ceil(4.2)); //redondea a 5(para arriba)
console.log(Math.max(45000, 75000, 38000)); //saca el mayor
console.log(Math.min(45000, 75000, 38000)); //saca el menor
console.log(Number.isInteger(2.75)); //es entero?(true or false)
